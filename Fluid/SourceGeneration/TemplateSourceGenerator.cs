using System.Text;
using Fluid.Ast;

namespace Fluid.SourceGeneration;

public static class TemplateSourceGenerator
{
    public static TemplateSource Generate(IFluidTemplate template, SourceGenerationOptions options = null)
    {
        ArgumentNullException.ThrowIfNull(template);

        options ??= new SourceGenerationOptions();

        if (template is not IStatementList rootStatementList)
        {
            throw new SourceGenerationException($"{template.GetType().FullName} is not compatible with source generation (it does not expose Statements).");
        }

        // Pre-compile the templates referenced by render, include and from
        var renderTemplates = CompileRenderTemplates(rootStatementList, options);

        var sb = new StringBuilder(capacity: 16 * 1024);

        WriteFileHeader(sb);

        sb.Append("namespace ").Append(options.Namespace).AppendLine();
        sb.AppendLine("{");

        // Map render path -> generated type name
        var renderTypeNames = new Dictionary<string, string>(StringComparer.Ordinal);
        var referencedTemplates = new Dictionary<string, IStatementList>(StringComparer.Ordinal);
        foreach (var kv in renderTemplates)
        {
            renderTypeNames[kv.Key] = kv.Value.ClassName;
            referencedTemplates[kv.Key] = kv.Value.Template;
        }

        // Loops only maintain their forloop variable when something can read it.
        var forLoopUsage = ForLoopUsageAnalysis.Analyze(rootStatementList, referencedTemplates);

        // Emit root class
        WriteTemplateClass(sb, options, options.ClassName, rootStatementList, renderTypeNames, forLoopUsage);

        // Emit subtemplate classes
        foreach (var kv in renderTemplates)
        {
            sb.AppendLine();
            WriteTemplateClass(sb, options, kv.Value.ClassName, kv.Value.Template, renderTypeNames, forLoopUsage, isPartial: true);
        }

        sb.AppendLine("}");

        return new TemplateSource(options.Namespace, options.ClassName, sb.ToString());
    }

    private static void WriteFileHeader(StringBuilder sb)
    {
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("#nullable enable");
        // Generated methods can be awaited uniformly, most are async even when they complete synchronously.
        sb.AppendLine("#pragma warning disable CS1998");
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using System.Globalization;");
        sb.AppendLine("using System.IO;");
        sb.AppendLine("using System.Linq;");
        sb.AppendLine("using System.Text.Encodings.Web;");
        sb.AppendLine("using System.Threading.Tasks;");
        sb.AppendLine("using Fluid;");
        sb.AppendLine("using Fluid.Ast;");
        sb.AppendLine("using Fluid.Utils;");
        sb.AppendLine("using Fluid.Values;");
        sb.AppendLine();
    }

    private static void WriteTemplateClass(
        StringBuilder sb,
        SourceGenerationOptions options,
        string className,
        IStatementList statementList,
        IReadOnlyDictionary<string, string> renderTemplateTypeNames,
        ForLoopUsageAnalysis forLoopUsage,
        bool isPartial = false)
    {
        var ctx = new SourceGenerationContext(sb, options, renderTemplateTypeNames) { ForLoopUsage = forLoopUsage };

        using (ctx.Indent())
        {
            ctx.WriteLine($"internal sealed class {className} : IFluidTemplate");
            ctx.WriteLine("{");
            using (ctx.Indent())
            {
                ctx.WriteLine("public async ValueTask RenderAsync(IFluidOutput writer, TextEncoder encoder, TemplateContext context)");
                ctx.WriteLine("{");
                using (ctx.Indent())
                {
                    ctx.WriteLine("if (writer == null) throw new ArgumentNullException(nameof(writer));");
                    ctx.WriteLine("if (encoder == null) throw new ArgumentNullException(nameof(encoder));");
                    ctx.WriteLine("if (context == null) throw new ArgumentNullException(nameof(context));");
                    ctx.WriteLine("context.CancellationToken.ThrowIfCancellationRequested();");
                    ctx.WriteLine("writer = LimitedFluidOutput.Create(writer, context.MaxOutputSize);");
                    ctx.WriteLine();

                    foreach (var statement in statementList.Statements)
                    {
                        // Avoid generating and invoking an extra method for pure text spans.
                        if (statement is TextSpanStatement textSpan)
                        {
                            textSpan.WriteTextTo(ctx);
                            continue;
                        }

                        // Like Liquid, a break or continue outside of a loop ends the template.
                        var methodName = ctx.GetStatementMethodName(statement);
                        ctx.WriteLine($"if (await {methodName}(writer, encoder, context) != Completion.Normal)");
                        ctx.WriteLine("{");
                        using (ctx.Indent())
                        {
                            ctx.WriteLine("await writer.FlushAsync();");
                            ctx.WriteLine("return;");
                        }
                        ctx.WriteLine("}");
                    }

                    ctx.WriteLine("context.CancellationToken.ThrowIfCancellationRequested();");
                    ctx.WriteLine("await writer.FlushAsync();");
                }
                ctx.WriteLine("}");

                if (isPartial)
                {
                    WriteStatementsMethod(ctx, statementList);
                }

                // Drain pending nodes and emit methods.
                var stmtIndex = 0;
                var exprIndex = 0;

                while (stmtIndex < ctx.PendingStatements.Count || exprIndex < ctx.PendingExpressions.Count)
                {
                    while (exprIndex < ctx.PendingExpressions.Count)
                    {
                        var expression = ctx.PendingExpressions[exprIndex++];
                        var methodName = ctx.GetExpressionMethodName(expression);

                        ctx.WriteLine();
                        ctx.WriteLine($"private static {GetMethodModifier(expression)}ValueTask<FluidValue> {methodName}(TemplateContext context)");
                        ctx.WriteLine("{");
                        using (ctx.Indent())
                        {
                            if (expression is ISourceable sourceableExpression)
                            {
                                sourceableExpression.WriteTo(ctx);
                            }
                            else
                            {
                                SourceGenerationContext.ThrowNotSourceable(expression);
                            }
                        }
                        ctx.WriteLine("}");
                    }

                    while (stmtIndex < ctx.PendingStatements.Count)
                    {
                        var statement = ctx.PendingStatements[stmtIndex++];
                        var methodName = ctx.GetStatementMethodName(statement);

                        ctx.WriteLine();
                        ctx.WriteLine($"private static {GetMethodModifier(statement)}ValueTask<Completion> {methodName}(IFluidOutput writer, TextEncoder encoder, TemplateContext context)");
                        ctx.WriteLine("{");
                        using (ctx.Indent())
                        {
                            if (statement is ISourceable sourceableStatement)
                            {
                                sourceableStatement.WriteTo(ctx);
                            }
                            else
                            {
                                SourceGenerationContext.ThrowNotSourceable(statement);
                            }
                        }
                        ctx.WriteLine("}");
                    }
                }

                ctx.WriteStaticMembers();
            }
            ctx.WriteLine("}");
        }
    }

    private static string GetMethodModifier(object node) => node is ISynchronousSourceable { IsSynchronous: true } ? "" : "async ";

    /// <summary>
    /// Emits the method <c>include</c> and <c>from</c> call: it writes the statements in the caller's scope and output,
    /// and returns their completion so that <c>break</c> and <c>continue</c> reach an enclosing loop.
    /// </summary>
    private static void WriteStatementsMethod(SourceGenerationContext ctx, IStatementList statementList)
    {
        ctx.WriteLine();
        ctx.WriteLine("public static async ValueTask<Completion> WriteStatementsAsync(IFluidOutput writer, TextEncoder encoder, TemplateContext context)");
        ctx.WriteLine("{");
        using (ctx.Indent())
        {
            ctx.WriteStatements(statementList.Statements);
            ctx.WriteLine("context.CancellationToken.ThrowIfCancellationRequested();");
            ctx.WriteLine("return Completion.Normal;");
        }
        ctx.WriteLine("}");
    }

    private sealed record CompiledRenderTemplate(string ClassName, IStatementList Template);

    private static Dictionary<string, CompiledRenderTemplate> CompileRenderTemplates(IStatementList rootTemplate, SourceGenerationOptions options)
    {
        var result = new Dictionary<string, CompiledRenderTemplate>(StringComparer.Ordinal);

        var visitor = new RenderDependencyVisitor();
        foreach (var statement in rootTemplate.Statements)
        {
            visitor.Visit(statement);
        }

        if (visitor.References.Count == 0)
        {
            return result;
        }

        if (options.TemplateContentResolver == null && options.FileProvider == null)
        {
            throw new SourceGenerationException(
                "SourceGenerationOptions.TemplateContentResolver or FileProvider is required to compile templates that use the 'render', 'include' or 'from' tags.");
        }

        var queue = new Queue<PartialReference>(visitor.References);
        var id = 0;

        while (queue.Count > 0)
        {
            var reference = queue.Dequeue();
            var path = reference.Path;

            if (result.ContainsKey(path))
            {
                continue;
            }

            var content = ReadTemplateContent(options, path);

            if (!reference.Parser.TryParse(content, out var parsedTemplate, out var errors))
            {
                throw new SourceGenerationException($"Failed to parse template '{path}'.", new ParseException(errors));
            }

            if (parsedTemplate is not IStatementList statementList)
            {
                throw new SourceGenerationException($"Template '{path}' is not compatible with source generation (it does not expose Statements).");
            }

            var className = options.ClassName + "__Render_" + (++id).ToString();
            result[path] = new CompiledRenderTemplate(className, statementList);

            // Enqueue nested render dependencies
            var nestedVisitor = new RenderDependencyVisitor();
            foreach (var statement in statementList.Statements)
            {
                nestedVisitor.Visit(statement);
            }
            foreach (var nested in nestedVisitor.References)
            {
                if (!result.ContainsKey(nested.Path))
                {
                    queue.Enqueue(nested);
                }
            }
        }

        return result;
    }

    private static string ReadTemplateContent(SourceGenerationOptions options, string relativePath)
    {
        if (options.TemplateContentResolver != null)
        {
            var content = options.TemplateContentResolver(relativePath);
            if (content == null)
            {
                throw new SourceGenerationException($"Template '{relativePath}' was not found by the provided TemplateContentResolver.");
            }

            return content;
        }

        var fileProvider = options.FileProvider;
        var fileInfo = fileProvider.GetFileInfo(relativePath);
        if (fileInfo == null || !fileInfo.Exists || fileInfo.IsDirectory)
        {
            throw new SourceGenerationException($"Template '{relativePath}' was not found in the provided FileProvider.");
        }

        using var stream = fileInfo.CreateReadStream();
        using var reader = new StreamReader(stream);
        return reader.ReadToEnd();
    }
}
